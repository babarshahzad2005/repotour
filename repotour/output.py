"""Writes rendered output identically on every platform, and never clobbers
a file Repotour did not write."""

from __future__ import annotations

from pathlib import Path

from repotour.errors import OutputError

MARKER = "<!-- generated by repotour -->"


def write_tour(path: Path, text: str, *, force: bool = False) -> None:
    """Write UTF-8 with LF line endings, refusing to overwrite foreign files."""
    if path.exists() and not force and not _is_generated(path):
        raise OutputError(
            f"{path} exists and was not generated by Repotour; "
            "use --out to write elsewhere or --force to overwrite it"
        )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.replace("\r\n", "\n").encode("utf-8"))


def _is_generated(path: Path) -> bool:
    with path.open("rb") as handle:
        return handle.read(len(MARKER)) == MARKER.encode("utf-8")
