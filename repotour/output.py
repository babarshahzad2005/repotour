"""Writes rendered output identically on every platform, and never clobbers
a file Repotour did not write."""

from __future__ import annotations

from collections.abc import Callable, Sequence
from dataclasses import dataclass
from pathlib import Path

from repotour.errors import OutputError

MARKER = "<!-- generated by repotour -->"


@dataclass(frozen=True)
class Output:
    """One file to write, with the test that tells whether Repotour wrote it."""

    path: Path
    text: str
    is_generated: Callable[[Path], bool]


def write_outputs(outputs: Sequence[Output], *, force: bool = False) -> None:
    """Write every output as UTF-8 with LF line endings, or none of them.

    All targets are checked before anything is written, so a refusal never
    leaves one file updated and another stale.
    """
    if not force:
        for output in outputs:
            if output.path.exists() and not output.is_generated(output.path):
                raise OutputError(
                    f"{output.path} exists and was not generated by Repotour; "
                    "use --out to write elsewhere or --force to overwrite it"
                )
    for output in outputs:
        output.path.parent.mkdir(parents=True, exist_ok=True)
        output.path.write_bytes(output.text.replace("\r\n", "\n").encode("utf-8"))


def has_marker(path: Path) -> bool:
    with path.open("rb") as handle:
        return handle.read(len(MARKER)) == MARKER.encode("utf-8")
